def prog2():
    """The same program with the accurate speed measurement: the Z80 routine REP (C580) repeats the
    transfer K times in one BASIC CALL, the window is 30 s and the 1 s granularity of TIME is corrected
    by half a second (H + .5)."""
    out = []
    drop = ('55 ', '60 ', '65 ')
    for ln in PROG:
        if ln.startswith(drop):
            continue
        if ln.startswith('50 '):
            ln = '50 WAIT 64 : PRINT "MEASURING THE BASIC CALL (20 S)" : WAIT 0'
        elif ln.startswith('52 '):
            ln = '52 A = 50528 : Z = 20 : GOSUB 1800 : OV = (H + .5) / N'
        elif ln.startswith('1000 '):
            ln = '1000 REM --- SPEED: 30 S EACH, K TRANSFERS PER CALL, MINUS OV ---'
        elif ln.startswith('1010 '):
            out.append('1005 Z = 30 : K = 20 : POKE 50682, K')
            ln = '1010 POKE TX, &88 : POKE IA, D, 1, 255 : A = 50560'
        elif ln.startswith('1020 '):
            out.append('1020 T = (H + .5) / N - OV : MS = INT (T / K * 1000 + .5)')
            ln = '1022 FQ = INT (2322 * K / T / 1000 + .5)'
        elif ln.startswith('1040 '):
            ln = '1040 T = (H + .5) / N - OV : FW = INT (2304 * K / T / 1000 + .5)'
        elif ln.startswith('1860 '):
            ln = '1860 IF H < Z THEN 1840'
        out.append(ln)
    return out


