#!/usr/bin/env python3
"""Generates the speed-lab drivers asm/i2c_z80_lab_v0.asm, _v1.asm, _v2.asm (same entry points and
main code, three versions of the bit loops) and the BASIC program Basic/pc1600_z80_speedlab-v2.0.txt.

V0: the loops of the driver v1.0 (a NOP in every clock, 3 port accesses and register copies when reading)
V1: V0 without the NOPs, and a shorter receive loop (no register copies)
V2: V1 with the send loop unrolled (BIT n,C instead of RLC C / DJNZ), the fastest version
The entry points are fixed (WH &C100, RH &C120, WL &C210, SL &C220, STH &C1F5, STL &C2F5), so the pages
&C100-&C2FF can be exchanged while the main code at &C400 stays. --check: DATA lines = assembler output."""
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
from z80asm_mini import Assembler

ROOT = os.path.join(here, '..')
V10 = open(os.path.join(ROOT, 'asm', 'i2c_z80_v1.0.asm')).read()

EQUS = V10[V10.index('HV      EQU'):V10.index('; ---------------------------------------------------------------------\n; page H1')]
MAIN = V10[V10.index('        ORG 0C400h'):]
MAIN = MAIN.replace('IC:     LD A,S_L1', 'IC:     LD A,S_L1')   # unchanged

BENCH = '''
; ---------------------------------------------------------------------
; port benchmark: 2560 port accesses per call (BASIC times the calls with TIME)
; ---------------------------------------------------------------------
        ORG 0C500h
BO:     DI                      ; (the first byte, 243, marks the lab version)
        LD A,S_L1
        LD B,0
BO1:
''' + '        OUT (OPC),A\n' * 10 + '''        DJNZ BO1
        EI
        RET
        ORG 0C520h
BI:     DI
        LD B,0
BI1:
''' + '        IN A,(PBP)\n' * 10 + '''        DJNZ BI1
        EI
        RET
        ORG 0C540h
BN:     DI
        LD B,0
BN1:
''' + '        NOP\n' * 10 + '''        DJNZ BN1
        EI
        RET
        ORG 0C560h
BR:     RET                     ; empty routine: measures the time of the BASIC CALL itself
'''


BENCH2 = '''
; ---------------------------------------------------------------------
; C500: marker (the first byte, 243, tells the BASIC program that the driver is installed)
; C560: empty routine (the time of the BASIC CALL itself is measured with it)
; C580: REP, calls the driver (C400) K times (K = byte at C5FA), stops at an error. For the speed
;       measurement: one BASIC CALL then lasts about one second and the BASIC overhead is small.
;       The interrupts are NOT disabled here (the driver does it for each transfer and restores
;       them), so the clock of BASIC (TIME) keeps running as in a normal program.
; ---------------------------------------------------------------------
        ORG 0C500h
BO:     DI
        EI
        RET
        ORG 0C560h
BR:     RET
        ORG 0C580h
REP:    LD A,(RPT)
        LD (RCT),A
RP1:    CALL IC
        LD A,E                  ; IC returns the status in E
        OR A
        JR NZ,RP2
        LD A,(RCT)
        DEC A
        LD (RCT),A
        JR NZ,RP1
RP2:    RET
'''


def header(v):
    names = {0: 'V0: loops of the driver v1.0 (a NOP in every clock)',
             1: 'V1: no NOPs, shorter receive loop',
             2: 'V2: V1 with the send loop unrolled',
             3: 'V3: V2 with the receive loop unrolled (in the H2 page)',
             4: 'V4: write block in the page code (no CALL per byte, counter in E)',
             5: 'V5: V4 + read block in the page code',
             6: 'V6: V5 with OUT (C),r clocks (B = SDA state, C = 18H, D = 80H, E = byte)',
             7: 'V7: V6 with I = B (cheaper state change)',
             8: 'V8: V5 with the clock values in registers (LD A,r)',
             9: 'V9: V8 with I = 0/1 (INC A / DEC A state change)',
             10: 'V10: V7 with INC B / DEC B state changes'}
    return ('; =====================================================================\n'
            '; I2C master Z80 for the PC-1600, speed lab, %s\n'
            '; Generated by tools/make_lab.py from asm/i2c_z80_v1.0.asm (main code) with fixed entry points.\n'
            '; Principle, pins and rules: see i2c_z80_v1.0.asm (SDA = page of the code + I register, A8 = pin 31).\n'
            '; Entry points: WH &C100  RH &C120  STH &C1F5 | STT &C200  WL &C210  SL &C220  STL &C2F5\n'
            '; =====================================================================\n\n' % names[v])


def pages(v):
    nop = '        NOP\n' if v == 0 else ''
    s = ['        ORG 0C100h\n']
    s.append('WH:     LD A,S_H1\n        OUT (OPC),A\n' + nop + '        IN A,(PBP)\n        LD D,A\n'
             '        LD A,S_L1\n        OUT (OPC),A\n        RET\n')
    s.append('        ORG 0C120h\n')
    if v == 3:
        s.append('RH:     JP RH2\n')
    elif v == 0:
        s.append('RH:     LD A,S_H1\n        OUT (OPC),A\n        NOP\n        IN A,(PBP)\n        LD D,A\n'
                 '        LD A,S_L1\n        OUT (OPC),A\n        LD A,D\n        RRA\n        RRA\n        RRA\n'
                 '        RL E\n        DJNZ RH\n        RET\n')
    else:
        s.append('RH:     LD A,S_H1\n        OUT (OPC),A\n        IN A,(PBP)\n        RRA             ; bit 2 -> carry\n'
                 '        RRA\n        RRA\n        LD A,S_L1       ; LD and OUT do not change the carry\n'
                 '        OUT (OPC),A\n        RL E\n        DJNZ RH\n        RET\n')
    s.append('        ORG 0C140h\n')
    if v < 2:
        s.append('SH:     RLC C\n        JP NC,SH_L\nSH_CLK: LD A,S_H1\n        OUT (OPC),A\n' + nop +
                 '        LD A,S_L1\n        OUT (OPC),A\n        DJNZ SH\n        JP WH\n'
                 'SH_L:   LD A,LV\n        LD I,A\n        JP SL_CLK\n')
    else:
        for k in range(7, -1, -1):
            s.append('SH%d:    BIT %d,C\n        JP Z,TL%d\nSH%dC:   LD A,S_H1\n        OUT (OPC),A\n'
                     '        LD A,S_L1\n        OUT (OPC),A\n' % (k, k, k, k))
        s.append('        JP WH\n')
        for k in range(7, -1, -1):
            s.append('TL%d:    LD A,LV\n        LD I,A\n        JP SL%dC\n' % (k, k))
    s.append('        ORG 0C1F5h\nSTH:    LD A,S_H1\n        OUT (OPC),A\n        NOP\n        NOP\n        NOP\n'
             '        LD A,LV\n        LD I,A\n')
    s.append('        ORG 0C200h\nSTT:    NOP\n        NOP\n        LD A,S_L0\n        OUT (OPC),A\n        RET\n')
    s.append('        ORG 0C210h\nWL:     LD A,S_H0\n        OUT (OPC),A\n' + nop +
             '        LD A,S_L0\n        OUT (OPC),A\n        RET\n')
    s.append('        ORG 0C220h\n')
    if v < 2:
        s.append('SL:     RLC C\n        JP C,SL_H\nSL_CLK: LD A,S_H0\n        OUT (OPC),A\n' + nop +
                 '        LD A,S_L0\n        OUT (OPC),A\n        DJNZ SL\n        LD A,HV\n        LD I,A\n'
                 '        JP WH\nSL_H:   LD A,HV\n        LD I,A\n        JP SH_CLK\n')
    else:
        for k in range(7, -1, -1):
            lab = 'SL:' if k == 7 else ''
            s.append('%-8sBIT %d,C\n        JP NZ,TH%d\nSL%dC:   LD A,S_H0\n        OUT (OPC),A\n'
                     '        LD A,S_L0\n        OUT (OPC),A\n' % (lab, k, k, k))
        s.append('        LD A,HV\n        LD I,A\n        JP WH\n')
        for k in range(7, -1, -1):
            s.append('TH%d:    LD A,HV\n        LD I,A\n        JP SH%dC\n' % (k, k))
    s.append('        ORG 0C2F5h\nSTL:    LD A,S_H0\n        OUT (OPC),A\n        NOP\n        NOP\n        NOP\n'
             '        LD A,HV\n        LD I,A\n')
    s.append('        ORG 0C300h\nSTP2:   NOP\n        NOP\n        NOP\n        LD A,S_L1\n        OUT (OPC),A\n        RET\n')
    if v == 3:
        s.append('        ORG 0C310h\nRH2:\n')      # eight receive clocks, no loop (in the H2 page: A8 = 1)
        for k in range(8):
            s.append('        LD A,S_H1\n        OUT (OPC),A\n        IN A,(PBP)\n        RRA\n        RRA\n        RRA\n'
                     '        LD A,S_L1\n        OUT (OPC),A\n        RL E\n')
        s.append('        RET\n')
    return ''.join(s)


def source(v):
    if v >= 8:
        import lab_v8plus as L8
        eq = EQUS + 'TXH     EQU 0C7h\nRPT     EQU 0C5FAh\nRCT     EQU 0C5F9h\n'
        if v >= 9:
            eq = eq.replace('HV      EQU 0C1h', 'HV      EQU 01h').replace('LV      EQU 0C2h', 'LV      EQU 00h')
        return header(v) + eq + L8.pages(v) + '\n' + L8.main(v, MAIN) + '\n' + BENCH2
    if v >= 4:
        import lab_v4plus as L
        eq = EQUS
        eq += 'TXH     EQU 0C7h\nRPT     EQU 0C5FAh\nRCT     EQU 0C5F9h\n'
        if v == 7:
            eq = eq.replace('HV      EQU 0C1h', 'HV      EQU 01h').replace('LV      EQU 0C2h', 'LV      EQU 00h')
        return header(v) + eq + L.pages(v) + '\n' + L.main(v, MAIN) + '\n' + BENCH2.replace('BO:     DI\n        EI', 'BO:     DI\n        EI') 
    return header(v) + EQUS + pages(v) + '\n' + MAIN.rstrip('\n') + '\n' + BENCH


def production_source():
    """The Z80 driver v1.1 = lab version V10 (OUT (C),r clocks, I = 0/1, INC B / DEC B state changes)
    without the lab routines at C500 and later."""
    import lab_v8plus as L8
    eq = (EQUS + 'TXH     EQU 0C7h\n').replace('HV      EQU 0C1h', 'HV      EQU 01h').replace('LV      EQU 0C2h', 'LV      EQU 00h')
    head = ('; =====================================================================\n'
            '; I2C master Z80 for the PC-1600, version 1.1 (speed lab version V10)\n'
            '; Same interface as v1.0:  POKE &C5FC,D,W,R : CALL &C400,E  (see i2c_z80_v1.0.asm)\n'
            '; SDA = page of the code + I register (A8 = pin 31), SCL = OPC bit 7 (pin 29), SDA read = PB2 (pin 27).\n'
            '; Generated by tools/make_lab.py from the lab sources; 56 kHz in the simulator, about 43 kHz read /\n'
            '; 54 kHz write on the real PC-1600 (reading a port costs about 28 T there, not 11 T).\n'
            '; Registers in the bit loops: B = SDA state (0/1, also the high address byte of OUT (C),r), C = 18h (OPC),\n'
            '; D = 80h (SCL high), E = data byte, HL = buffer pointer; I = B.\n'
            '; =====================================================================\n\n')
    tail = '''
; ---------------------------------------------------------------------
; C560: empty routine (the BASIC program times it to subtract the time of the BASIC CALL itself)
; C580: REP, calls the driver K times (K = byte at C5FA) and stops at an error. The BMP280 program
;       uses it to measure the I2C speed; the interrupts stay enabled between the transfers.
; ---------------------------------------------------------------------
        ORG 0C560h
BR:     RET
        ORG 0C580h
REP:    LD A,(RPT)
        LD (RCT),A
RP1:    CALL IC
        LD A,E
        OR A
        JR NZ,RP2
        LD A,(RCT)
        DEC A
        LD (RCT),A
        JR NZ,RP1
RP2:    RET
'''
    return head + eq + 'RPT     EQU 0C5FAh\nRCT     EQU 0C5F9h\n' + L8.pages(10) + '\n' + L8.main(10, MAIN) + tail


def asm_of(v):
    a = Assembler()
    a.assemble(source(v))
    return a


def write_sources():
    pa = Assembler()
    pa.assemble(production_source())
    pp = os.path.join(ROOT, 'asm', 'i2c_z80_v1.1.asm')
    open(pp, 'w').write(production_source())
    open(pp.replace('.asm', '.lst'), 'w').write(pa.list_text())
    print('v1.1: %d bytes in %d segments' % (len(pa.image), len(pa.segments())))
    for v in range(11):
        p = os.path.join(ROOT, 'asm', 'i2c_z80_lab_v%d.asm' % v)
        open(p, 'w').write(source(v))
        a = asm_of(v)
        open(p.replace('.asm', '.lst'), 'w').write(a.list_text())
        print('V%d: %d bytes in %d segments' % (v, len(a.image), len(a.segments())))



